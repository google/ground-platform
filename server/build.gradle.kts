// The repository root's local.properties, then this module's own (whose values win).
val localProperties =
  Properties().apply {
    for (dir in listOf(layout.settingsDirectory, layout.projectDirectory)) {
      providers.fileContents(dir.file("local.properties")).asText.orNull?.let { load(it.reader()) }
    }
  }

val eeServiceAccountFile =
  (providers.gradleProperty("EE_SERVICE_ACCOUNT_FILE").orNull
      ?: providers.environmentVariable("EE_SERVICE_ACCOUNT_FILE").orNull
      ?: localProperties.getProperty("EE_SERVICE_ACCOUNT_FILE")
      ?: "")
    .trim()

val eeProjectId =
  (providers.gradleProperty("EE_PROJECT_ID").orNull
      ?: providers.environmentVariable("EE_PROJECT_ID").orNull
      ?: localProperties.getProperty("EE_PROJECT_ID")
      ?: "")
    .trim()

val generateServerBuildConfig by tasks.registering {
  val fileProp = eeServiceAccountFile
  val projectProp = eeProjectId
  inputs.property("eeServiceAccountFile", fileProp)
  inputs.property("eeProjectId", projectProp)
  val outputDir =
    layout.buildDirectory.dir("generated/serverConfig/org/openforis/collectone/v2/server/geo")
  val generatedRoot = layout.buildDirectory.dir("generated/serverConfig")
  outputs.dir(generatedRoot)
  doLast {
    // Drop configs generated into an earlier package.
    generatedRoot.get().asFile.deleteRecursively()
    val fileValue = if (fileProp.isEmpty()) "null" else "\"$fileProp\""
    val projectValue = if (projectProp.isEmpty()) "null" else "\"$projectProp\""
    outputDir
      .get()
      .file("ServerBuildConfig.kt")
      .asFile
      .apply { parentFile.mkdirs() }
      .writeText(
        "// Generated by build.gradle.kts; do not edit.\n" +
          "package org.openforis.collectone.v2.server.geo\n\n" +
          "object ServerBuildConfig {\n" +
          "  val eeServiceAccountFile: String? = $fileValue\n" +
          "  val eeProjectId: String? = $projectValue\n" +
          "}\n"
      )
  }
}

sourceSets.main {
  kotlin.srcDir(layout.buildDirectory.dir("generated/serverConfig"))
}

tasks.named("compileKotlin") {
  dependsOn(generateServerBuildConfig)
}

tasks.named<JavaExec>("run") {
  if (eeServiceAccountFile.isNotEmpty()) {
    environment("EE_SERVICE_ACCOUNT_FILE", eeServiceAccountFile)
  }
  if (eeProjectId.isNotEmpty()) {
    environment("EE_PROJECT_ID", eeProjectId)
  }
  for (key in
    listOf(
      "BREVO_API_KEY",
      "EMAIL_FROM",
      "EMAIL_FROM_NAME",
      "EMAIL_MODE",
      "PUBLIC_WEB_URL",
      "WHISP_API_KEY",
      "WHISP_API_URL",
      "WHISP_PREFIX",
    )) {
    val value =
      (providers.environmentVariable(key).orNull ?: localProperties.getProperty(key) ?: "").trim()
    if (value.isNotEmpty()) {
      environment(key, value)
    }
  }
}

// Spanner proto bundle: a FileDescriptorSet of shared/protos (with their google/protobuf and
// google/type imports), generated with protoc and packaged as the `spanner/descriptors.pb`
// resource. SpannerSchema sends it with `CREATE PROTO BUNDLE` / `ALTER PROTO BUNDLE`.
val protocVersion = libs.versions.protobuf.get()
val protoc: Configuration by configurations.creating
val protoIncludes: Configuration by configurations.creating { isTransitive = false }

dependencies {
  protoc("com.google.protobuf:protoc:$protocVersion:${protocClassifier()}@exe")
  protoIncludes(libs.protobuf.java)
  protoIncludes(libs.google.common.protos)
}

fun protocClassifier(): String {
  val os = System.getProperty("os.name").lowercase()
  val arch =
    if (System.getProperty("os.arch") in setOf("aarch64", "arm64")) "aarch_64" else "x86_64"
  return when {
    os.contains("mac") -> "osx-$arch"
    os.contains("win") -> "windows-$arch"
    else -> "linux-$arch"
  }
}

val spannerProtosDir = layout.buildDirectory.dir("spannerProtos")
val spannerResourcesDir = layout.buildDirectory.dir("generated/spannerResources")

val stageSpannerProtos by
  tasks.registering(Sync::class) {
    from("../shared/protos") { include("**/*.proto") }
    into(spannerProtosDir.map { it.dir("src/shared/protos") })
  }

/** Unpacks archives in task inputs without referencing this script (configuration cache). */
interface ArchiveServices {
  @get:Inject val archives: ArchiveOperations
}

val extractSpannerProtoIncludes by
  tasks.registering(Sync::class) {
    val archives = objects.newInstance<ArchiveServices>().archives
    from(protoIncludes.elements.map { files -> files.map { archives.zipTree(it) } }) {
      include("google/protobuf/*.proto", "google/type/*.proto")
    }
    into(spannerProtosDir.map { it.dir("include") })
  }

val generateSpannerDescriptors by
  tasks.registering(Exec::class) {
    dependsOn(stageSpannerProtos, extractSpannerProtoIncludes)
    val sources = spannerProtosDir.map { it.dir("src") }
    val includes = spannerProtosDir.map { it.dir("include") }
    val output = spannerResourcesDir.map { it.file("spanner/descriptors.pb") }
    val protocExecutable: FileCollection = protoc
    inputs.files(protocExecutable, stageSpannerProtos, extractSpannerProtoIncludes)
    outputs.file(output)
    doFirst {
      val exe = protocExecutable.singleFile.apply { setExecutable(true) }
      output.get().asFile.parentFile.mkdirs()
      val src = sources.get().asFile
      val protos =
        src
          .walkTopDown()
          .filter { it.extension == "proto" }
          .map { it.relativeTo(src).path }
          .sorted()
      executable = exe.absolutePath
      args(
        listOf(
          "-I${src.absolutePath}",
          "-I${includes.get().asFile.absolutePath}",
          "--include_imports",
          "--descriptor_set_out=${output.get().asFile.absolutePath}",
        ) + protos.toList()
      )
    }
  }

sourceSets.main { resources.srcDir(spannerResourcesDir) }

tasks.processResources { dependsOn(generateSpannerDescriptors) }

// Unit tests run on an in-memory fake store. Tests tagged `spanner` need the Spanner emulator, and
// run with `./gradlew :server:spannerTest`: on the emulator at SPANNER_EMULATOR_HOST, or on one the
// tests
// start from scripts/spanner-emulator.sh. The `load` test runs only with `./gradlew
// :server:loadTest`.
tasks.test { useJUnitPlatform { excludeTags("spanner", "load") } }

val spannerTest by
  tasks.registering(Test::class) {
    description = "Runs the tests that need the Spanner emulator."
    group = "verification"
    testClassesDirs = sourceSets.test.get().output.classesDirs
    classpath = sourceSets.test.get().runtimeClasspath
    useJUnitPlatform { includeTags("spanner") }
    shouldRunAfter(tasks.test)
  }

// Local load test on the Spanner emulator (never a deployed server): concurrent mixed reads and
// mutations at each RPC parallelism. -Pload.parallelism=1,8, -Pload.clients, and
// -Pload.requestsPerClient tune it.
val loadTest by
  tasks.registering(Test::class) {
    description = "Runs the local load test against the Spanner emulator."
    group = "verification"
    testClassesDirs = sourceSets.test.get().output.classesDirs
    classpath = sourceSets.test.get().runtimeClasspath
    useJUnitPlatform { includeTags("load") }
    outputs.upToDateWhen { false }
    testLogging.showStandardStreams = true
    listOf("load.parallelism", "load.clients", "load.requestsPerClient").forEach { name ->
      providers.gradleProperty(name).orNull?.let { systemProperty(name, it) }
    }
  }

// Coverage counts the unit tests only: the Spanner and load tests need an emulator, and a report
// (`./gradlew :koverXmlReport`) must not start them.
kover {
  currentProject { instrumentation { disabledForTestTasks.addAll("spannerTest", "loadTest") } }
}
