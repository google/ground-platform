package org.openforis.collectone.v2.server.geo

import com.squareup.moshi.Types
import google.earthengine.v1main.Expression
import google.earthengine.v1main.FunctionInvocation
import google.earthengine.v1main.ValueNode
import io.grpc.Status
import openforis.collectone.v1.survey.SceneStretch
import org.openforis.collectone.v2.server.web.protoJsonMoshi

/**
 * An Earth Engine expression template generated by `tools/earthengine/generate_templates.py`: an
 * [Expression] whose result is a `FunctionDefinition` with named arguments.
 */
internal class EarthEngineTemplate(val name: String, val version: Int, val expression: Expression) {
  /** Names of the function's arguments, in declaration order. */
  val argumentNames: List<String> =
    expression.values[expression.result]?.function_definition_value?.argument_names.orEmpty()

  /**
   * An expression that calls this template's function with [arguments] (argument name to value),
   * referring to the definition through `function_reference`.
   */
  fun invoke(arguments: Map<String, ValueNode>): Expression {
    require(arguments.keys == argumentNames.toSet()) {
      "Template $name takes $argumentNames, got ${arguments.keys}"
    }
    val invocation =
      ValueNode(
        function_invocation_value =
          FunctionInvocation(function_reference = expression.result, arguments = arguments)
      )
    return Expression(
      values = expression.values + (INVOCATION_KEY to invocation),
      result = INVOCATION_KEY,
    )
  }

  companion object {
    /** Value key of the invocation; generated templates only use numeric keys. */
    private const val INVOCATION_KEY = "c1Invoke"

    private val mapAdapter =
      protoJsonMoshi.adapter<Map<String, Any?>>(
        Types.newParameterizedType(Map::class.java, String::class.java, Any::class.java)
      )
    private val expressionAdapter = protoJsonMoshi.adapter(Expression::class.java)

    /** Loads `src/main/resources/earthengine/<name>.json`. */
    fun load(name: String): EarthEngineTemplate {
      val text =
        EarthEngineTemplate::class.java.getResourceAsStream("/earthengine/$name.json")?.use {
          it.readBytes().decodeToString()
        } ?: error("Missing Earth Engine template $name")
      val root = mapAdapter.fromJson(text) ?: error("Empty Earth Engine template $name")
      val version =
        (root["templateVersion"] as? Number)?.toInt()
          ?: error("Earth Engine template $name has no templateVersion")
      val expression =
        expressionAdapter.fromJsonValue(root["expression"])
          ?: error("Earth Engine template $name has no expression")
      val template = EarthEngineTemplate(name, version, expression)
      check(template.argumentNames.isNotEmpty()) {
        "Earth Engine template $name doesn't evaluate to a function"
      }
      return template
    }
  }
}

/** Builders for Earth Engine expression nodes. */
internal object EarthEngineNodes {
  /** A constant; numbers become doubles, the only number type of `google.protobuf.Value`. */
  fun constant(value: Any?): ValueNode = ValueNode(constant_value = jsonValue(value))

  private fun jsonValue(value: Any?): Any? =
    when (value) {
      is Number -> value.toDouble()
      is List<*> -> value.map(::jsonValue)
      is Map<*, *> -> value.mapValues { (_, v) -> jsonValue(v) }
      else -> value
    }

  fun call(name: String, vararg arguments: Pair<String, ValueNode>): ValueNode =
    ValueNode(
      function_invocation_value =
        FunctionInvocation(function_name = name, arguments = arguments.toMap())
    )

  /** A single-node expression evaluating [node]. */
  fun expression(node: ValueNode): Expression =
    Expression(values = mapOf("0" to node), result = "0")

  fun point(longitude: Double, latitude: Double): ValueNode =
    call("GeometryConstructors.Point", "coordinates" to constant(listOf(longitude, latitude)))

  /** A polygon from one closed ring of `[longitude, latitude]` pairs. */
  fun polygon(ring: List<List<Double>>): ValueNode =
    call(
      "GeometryConstructors.Polygon",
      "coordinates" to constant(listOf(ring)),
      "evenOdd" to constant(true),
    )
}

/**
 * Historical scenes that `GetSceneTileUrl` may visualize: the collections the time series templates
 * read. Each kind maps optical stretches to its band names and display ranges.
 */
internal enum class SceneKind(
  private val collectionIds: List<String>,
  val attribution: String,
  private val bands: Map<SceneStretch, List<String>>,
  private val max: Map<SceneStretch, List<Double>>,
) {
  /** Landsat 8 and 9 OLI, TOA reflectance (0–1). */
  LANDSAT_OLI(
    listOf("LANDSAT/LC09/C02/T1_TOA", "LANDSAT/LC08/C02/T1_TOA"),
    LANDSAT_ATTRIBUTION,
    mapOf(
      SceneStretch.TRUE_COLOR to listOf("B4", "B3", "B2"),
      SceneStretch.SWIR_NIR_RED to listOf("B6", "B5", "B4"),
      SceneStretch.NIR_SWIR_RED to listOf("B5", "B6", "B4"),
    ),
    REFLECTANCE_MAX,
  ),

  /** Landsat 4 and 5 TM and Landsat 7 ETM+, TOA reflectance (0–1). */
  LANDSAT_TM_ETM(
    listOf("LANDSAT/LE07/C02/T1_TOA", "LANDSAT/LT05/C02/T1_TOA", "LANDSAT/LT04/C02/T1_TOA"),
    LANDSAT_ATTRIBUTION,
    mapOf(
      SceneStretch.TRUE_COLOR to listOf("B3", "B2", "B1"),
      SceneStretch.SWIR_NIR_RED to listOf("B5", "B4", "B3"),
      SceneStretch.NIR_SWIR_RED to listOf("B4", "B5", "B3"),
    ),
    REFLECTANCE_MAX,
  ),

  /** Sentinel-2 surface reflectance, scaled by 10,000. */
  SENTINEL_2(
    listOf("COPERNICUS/S2_SR_HARMONIZED"),
    SENTINEL_ATTRIBUTION,
    mapOf(
      SceneStretch.TRUE_COLOR to listOf("B4", "B3", "B2"),
      SceneStretch.SWIR_NIR_RED to listOf("B11", "B8", "B4"),
      SceneStretch.NIR_SWIR_RED to listOf("B8", "B11", "B4"),
    ),
    REFLECTANCE_MAX.mapValues { (_, max) -> max.map { it * 10_000 } },
  ),

  /** Sentinel-1 GRD backscatter (dB). */
  SENTINEL_1(listOf("COPERNICUS/S1_GRD"), SENTINEL_ATTRIBUTION, emptyMap(), emptyMap());

  val isOptical: Boolean
    get() = this != SENTINEL_1

  /** Stretch used when the request doesn't name a supported one. */
  val defaultStretch: SceneStretch
    get() = if (isOptical) SceneStretch.TRUE_COLOR else SceneStretch.SAR_VV_VH_RATIO

  fun supports(stretch: SceneStretch): Boolean =
    if (isOptical) stretch in bands else stretch == SceneStretch.SAR_VV_VH_RATIO

  /** Visualization of scene [sceneId] with [stretch] (which must be [supports]ed). */
  fun visualization(sceneId: String, stretch: SceneStretch): Expression {
    val image = EarthEngineNodes.call("Image.load", "id" to EarthEngineNodes.constant(sceneId))
    return if (isOptical) {
      val selected =
        EarthEngineNodes.call(
          "Image.select",
          "input" to image,
          "bandSelectors" to EarthEngineNodes.constant(bands.getValue(stretch)),
        )
      EarthEngineNodes.expression(
        EarthEngineNodes.call(
          "Image.visualize",
          "image" to selected,
          "min" to EarthEngineNodes.constant(listOf(0.0, 0.0, 0.0)),
          "max" to EarthEngineNodes.constant(max.getValue(stretch)),
          "gamma" to
            EarthEngineNodes.constant(if (stretch == SceneStretch.TRUE_COLOR) 1.4 else 1.2),
        )
      )
    } else {
      sarVisualization(image)
    }
  }

  /** VV, VH, and their dB ratio, with Collect Earth Online Geo-Dash's display ranges. */
  private fun sarVisualization(image: ValueNode): Expression {
    fun select(input: ValueNode, vararg bands: String) =
      EarthEngineNodes.call(
        "Image.select",
        "input" to input,
        "bandSelectors" to EarthEngineNodes.constant(bands.toList()),
      )
    val polarizations = select(image, "VV", "VH")
    val ratio =
      EarthEngineNodes.call(
        "Image.rename",
        "input" to
          EarthEngineNodes.call(
            "Image.divide",
            "image1" to select(polarizations, "VV"),
            "image2" to select(polarizations, "VH"),
          ),
        "names" to EarthEngineNodes.constant(listOf("VV/VH")),
      )
    return EarthEngineNodes.expression(
      EarthEngineNodes.call(
        "Image.visualize",
        "image" to
          EarthEngineNodes.call("Image.addBands", "dstImg" to polarizations, "srcImg" to ratio),
        "bands" to EarthEngineNodes.constant(listOf("VV", "VH", "VV/VH")),
        "min" to EarthEngineNodes.constant(listOf(-15.0, -25.0, 0.4)),
        "max" to EarthEngineNodes.constant(listOf(0.0, -10.0, 1.0)),
        "gamma" to EarthEngineNodes.constant(1.6),
      )
    )
  }

  companion object {
    private val SCENE_NAME = Regex("[A-Za-z0-9_]+")

    /** The kind of scene [sceneId], or `null` if it isn't from an allowed collection. */
    fun of(sceneId: String): SceneKind? {
      val collectionId = sceneId.substringBeforeLast('/', missingDelimiterValue = "")
      val sceneName = sceneId.substringAfterLast('/')
      if (!SCENE_NAME.matches(sceneName)) return null
      return entries.firstOrNull { collectionId in it.collectionIds }
    }

    /** Throws `INVALID_ARGUMENT` unless [sceneId] is from an allowed collection. */
    fun require(sceneId: String): SceneKind =
      of(sceneId)
        ?: throw Status.INVALID_ARGUMENT.withDescription(
            "scene_id must be a Landsat, Sentinel-2, or Sentinel-1 scene from a time series"
          )
          .asRuntimeException()
  }
}

internal const val LANDSAT_ATTRIBUTION = "Landsat imagery courtesy of the U.S. Geological Survey"
internal const val SENTINEL_ATTRIBUTION = "Contains modified Copernicus Sentinel data"

/** Top of the display range of each optical stretch, in reflectance (0–1). */
private val REFLECTANCE_MAX: Map<SceneStretch, List<Double>> =
  mapOf(
    SceneStretch.TRUE_COLOR to listOf(0.3, 0.3, 0.3),
    SceneStretch.SWIR_NIR_RED to listOf(0.45, 0.5, 0.3),
    SceneStretch.NIR_SWIR_RED to listOf(0.5, 0.45, 0.3),
  )
