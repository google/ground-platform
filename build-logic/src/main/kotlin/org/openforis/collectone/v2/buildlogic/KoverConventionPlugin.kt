package org.openforis.collectone.v2.buildlogic

import kotlinx.kover.gradle.plugin.dsl.KoverProjectExtension
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.kotlin.dsl.configure

/**
 * `collectone.kover`: coverage of the JVM tests, in the `jvmTests` report variant (`./gradlew
 * :<module>:koverHtmlReportJvmTests` or `koverXmlReportJvmTests`). Kover's default (total) variant
 * would also run the Android unit tests of the Android targets, which CI doesn't run. The root
 * project applies the plugin too and merges the `jvmTests` variant of every covered module into one
 * report (`./gradlew :koverHtmlReportJvmTests :koverVerifyJvmTests`); generated code is excluded
 * here, where both the module and the merged reports pick it up.
 */
class KoverConventionPlugin : Plugin<Project> {
  override fun apply(target: Project): Unit =
    with(target) {
      pluginManager.apply("org.jetbrains.kotlinx.kover")
      if (this != rootProject) {
        rootProject.pluginManager.withPlugin("collectone.kover") {
          rootProject.dependencies.add("kover", this@with)
        }
      }
      extensions.configure<KoverProjectExtension> {
        // The Kotlin Multiplatform JVM target or a Kotlin/JVM module; the root project has neither.
        currentProject { createVariant(JVM_TESTS_VARIANT) { add("jvm", optional = true) } }
        reports { filters { excludes { classes(GENERATED_CLASSES) } } }
      }
    }

  companion object {
    /** The report variant with the JVM tests only, whose tasks end in `JvmTests`. */
    const val JVM_TESTS_VARIANT = "jvmTests"

    /** Classes generated at build time, which the tests have no reason to cover. */
    private val GENERATED_CLASSES =
      listOf(
        // Wire messages of shared/protos (shared/core), named after the proto packages.
        "openforis.collectone.v1.*",
        "google.earthengine.*",
        "com.google.type.*",
        // The SQLDelight database (shared/app/data).
        "org.openforis.collectone.v2.app.data.datasource.local.db.*",
        // Compose resource accessors (`Res`): the modules' packageOfResClass, and the default.
        "org.openforis.collectone.v2.app.resources.*",
        "org.openforis.collectone.v2.web.resources.*",
        "org.openforis.collectone.v2.mobile.resources.*",
        "org.openforis.collectone.v2.core.forms.ui.resources.*",
        "*.generated.resources.*",
        // Lambdas the Compose compiler hoists out of composables.
        "*.ComposableSingletons*",
        // Build-time configuration objects generated by Gradle build scripts.
        "org.openforis.collectone.v2.app.domain.model.AppBuildConfig",
        "org.openforis.collectone.v2.server.geo.ServerBuildConfig",
      )
  }
}
