package org.openforis.collectone.v2.app.domain.model.editor

import org.openforis.collectone.v2.app.domain.model.DomainMessage
import org.openforis.collectone.v2.app.domain.model.message

/** A problem that prevents the Form from generating valid, unambiguous XForms. */
data class EditorIssue(
  val questionKey: String?,
  /** What is wrong, localized by the presentation layer (`ui/text/DomainMessageText.kt`). */
  val message: DomainMessage,
  /** Whether this is advice that never blocks publishing (e.g. concept link warnings). */
  val isWarning: Boolean = false,
  /** ID of the [EditorSection] the issue is about, when it's about a section's settings. */
  val sectionId: String? = null,
)

/** Structural validation of an [EditorForm]. */
object FormEditorValidator {
  private val NAME_PATTERN = Regex("^[A-Za-z_][A-Za-z0-9_.-]*$")
  private val RESERVED_NAMES = setOf("meta", "data")

  fun isValidName(name: String): Boolean = NAME_PATTERN.matches(name) && name !in RESERVED_NAMES

  fun validate(form: EditorForm, datasets: List<EditorDataset> = emptyList()): List<EditorIssue> {
    val issues = mutableListOf<EditorIssue>()
    // Form IDs are opaque: generated by FormIds or preserved verbatim from imported XForms.
    if (form.formId.isBlank()) {
      issues +=
        EditorIssue(
          null,
          message = EditorIssueMessage.FORM_MISSING_ID.message(),
        )
    }
    // Section IDs name instance nodes too, so a question can't share one.
    val nameCounts =
      (form.questions.map { it.name } + form.sections.map { it.id }).groupingBy { it }.eachCount()
    form.questions.forEachIndexed { index, question ->
      val key = question.key
      when {
        question.name.isBlank() ->
          issues +=
            EditorIssue(
              key,
              message = EditorIssueMessage.NAME_REQUIRED.message(),
            )
        !isValidName(question.name) ->
          issues +=
            EditorIssue(
              key,
              message = EditorIssueMessage.NAME_INVALID.message(),
            )
        (nameCounts[question.name] ?: 0) > 1 ->
          issues +=
            EditorIssue(
              key,
              message = EditorIssueMessage.NAME_DUPLICATE.message(question.name),
            )
      }
      if (question.label.isBlank()) {
        issues +=
          EditorIssue(
            key,
            message = EditorIssueMessage.LABEL_EMPTY.message(),
          )
      }
      if (question.type.hasChoices) {
        if (question.usesDatasetChoices) {
          val isDataTable = question.effectiveChoiceSource(datasets) == ChoiceSource.DATA_TABLE
          val choiceDatasetId = question.choiceDatasetId.orEmpty()
          val dataset = datasets.firstOrNull { it.id == choiceDatasetId }
          when {
            choiceDatasetId.isBlank() ->
              issues +=
                EditorIssue(
                  key,
                  message =
                    if (isDataTable) {
                      EditorIssueMessage.CHOOSE_CHOICE_DATA_TABLE.message()
                    } else {
                      EditorIssueMessage.CHOOSE_CHOICE_MAP_LAYER.message()
                    },
                )
            datasets.isNotEmpty() && dataset == null ->
              issues +=
                EditorIssue(
                  key,
                  message = EditorIssueMessage.CHOICE_DATASET_MISSING.message(choiceDatasetId),
                )
            question.allowAddEntity && dataset != null && dataset.isGenerated ->
              issues +=
                EditorIssue(
                  key,
                  message =
                    EditorIssueMessage.CHOICE_DATASET_GENERATED.message(dataset.displayName),
                )
            question.allowAddEntity &&
              dataset != null &&
              (dataset.key.isNotEmpty() || dataset.linkedFormKey != null) &&
              !dataset.hasCreationForm ->
              issues +=
                EditorIssue(
                  key,
                  message =
                    if (dataset.isMapLayer) {
                      EditorIssueMessage.CHOICE_DATASET_NO_CREATION_FORM_MAP_LAYER.message(
                        dataset.displayName
                      )
                    } else {
                      EditorIssueMessage.CHOICE_DATASET_NO_CREATION_FORM_DATA_TABLE.message(
                        dataset.displayName
                      )
                    },
                )
          }
        } else {
          if (question.choices.isEmpty()) {
            issues +=
              EditorIssue(
                key,
                message = EditorIssueMessage.ADD_CHOICE.message(),
              )
          }
          val values = question.choices.map { it.value }
          if (values.any { it.isBlank() || it.any(Char::isWhitespace) }) {
            issues +=
              EditorIssue(
                key,
                message = EditorIssueMessage.CHOICE_VALUE_INVALID.message(),
              )
          }
          if (values.toSet().size != values.size) {
            issues +=
              EditorIssue(
                key,
                message = EditorIssueMessage.CHOICE_VALUE_DUPLICATE.message(),
              )
          }
        }
      }
      relevanceIssue(form, question.relevance, index, question.sectionId)?.let {
        issues += EditorIssue(key, message = it)
      }
      if (!question.type.isReadOnly) {
        relevanceIssue(form, question.requiredCondition, index, question.sectionId)?.let {
          issues += EditorIssue(key, message = it)
        }
        relevanceIssue(form, question.validation?.condition, index, question.sectionId)?.let {
          issues += EditorIssue(key, message = it)
        }
      }
      issues += cascadeIssues(form, index, question, datasets)
      issues += ValidationRules.issues(question, form).map { EditorIssue(key, message = it) }
    }
    form.sections.forEach { section ->
      sectionRelevanceIssue(form, section)?.let {
        issues += EditorIssue(null, message = it, sectionId = section.id)
      }
    }
    form.googleEarthIncompatibleQuestions().forEach { question ->
      issues +=
        EditorIssue(
          question.key,
          message = googleEarthIncompatibleMessage(question),
        )
    }
    return issues
  }

  /**
   * What's wrong with display logic [relevance] of a question at [targetIndex] in section
   * [contextSectionId] (or of a section whose first question is at [targetIndex]), if anything.
   */
  private fun relevanceIssue(
    form: EditorForm,
    relevance: EditorRelevance?,
    targetIndex: Int,
    contextSectionId: String,
  ): DomainMessage? {
    relevance ?: return null
    val sourceIndex = form.indexOf(relevance.sourceQuestionKey)
    val source =
      form.questions.getOrNull(sourceIndex)
        ?: return EditorIssueMessage.DISPLAY_LOGIC_SOURCE_DELETED.message()
    return when {
      sourceIndex >= targetIndex ->
        EditorIssueMessage.DISPLAY_LOGIC_SOURCE_LATER.message(source.name)
      !form.canReferTo(source, contextSectionId) && form.sectionOf(source)?.repeatable == true ->
        EditorIssueMessage.DISPLAY_LOGIC_SOURCE_IN_REPEAT.message(source.name)
      relevance.operator !in RelevanceOperator.availableFor(source.type) ->
        EditorIssueMessage.DISPLAY_LOGIC_OPERATOR_NOT_APPLICABLE.message(
          DomainMessage.Label(relevance.operator),
          DomainMessage.Label(source.type),
        )
      relevance.operator.needsValue && relevance.value.isBlank() ->
        EditorIssueMessage.DISPLAY_LOGIC_VALUE_MISSING.message()
      source.type.isNumeric &&
        relevance.operator.needsValue &&
        relevance.value.toDoubleOrNull() == null ->
        EditorIssueMessage.DISPLAY_LOGIC_VALUE_NOT_NUMBER.message()
      else -> null
    }
  }

  /**
   * What's wrong with [section]'s display logic, if anything: like a question's, it must depend on
   * a question asked before the section, and it can't depend on one of its own questions.
   */
  private fun sectionRelevanceIssue(form: EditorForm, section: EditorSection): DomainMessage? {
    val relevance = section.relevance ?: return null
    val source = form.find(relevance.sourceQuestionKey)
    if (source != null && source.sectionId == section.id) {
      return EditorIssueMessage.SECTION_DISPLAY_LOGIC_SOURCE_INSIDE.message(source.name)
    }
    val firstIndex = form.firstQuestionIndex(section.id)
    return relevanceIssue(
      form,
      relevance,
      targetIndex = if (firstIndex >= 0) firstIndex else Int.MAX_VALUE,
      contextSectionId = "",
    )
  }

  /** Error shown for a question whose field type is not supported in Google Earth map balloons. */
  fun googleEarthIncompatibleMessage(question: EditorQuestion): DomainMessage =
    EditorIssueMessage.GOOGLE_EARTH_INCOMPATIBLE_QUESTION.message(
      question.label.ifBlank { question.name },
      DomainMessage.Label(question.type),
    )

  /**
   * Issues with [question]'s cascading-select parent (at [index] in [form]): the parent must still
   * exist, come before it, and be a choice question, like a display logic source. Choices tied to a
   * parent value the parent doesn't offer are never listed, which is advice rather than an error
   * since the parent's choices may still be in progress.
   */
  private fun cascadeIssues(
    form: EditorForm,
    index: Int,
    question: EditorQuestion,
    datasets: List<EditorDataset>,
  ): List<EditorIssue> {
    if (question.parentQuestionKey.isBlank() || !question.type.hasChoices) return emptyList()
    val key = question.key
    val parent =
      form.cascadeParentRefOf(question)
        ?: return listOf(EditorIssue(key, EditorIssueMessage.CASCADE_PARENT_DELETED.message()))
    val parentIndex = form.indexOf(parent.key)
    return when {
      parentIndex >= index ->
        listOf(EditorIssue(key, EditorIssueMessage.CASCADE_PARENT_LATER.message(parent.name)))
      !parent.type.hasChoices ->
        listOf(EditorIssue(key, EditorIssueMessage.CASCADE_PARENT_NOT_CHOICE.message(parent.name)))
      else -> {
        val parentValues = parent.resolvedChoices(datasets).map { it.value }.toSet()
        val unknown =
          if (question.usesDatasetChoices || parentValues.isEmpty()) {
            emptyList()
          } else {
            question.choices
              .map { it.parentValue.trim() }
              .filter { it.isNotEmpty() && it !in parentValues }
              .distinct()
          }
        if (unknown.isEmpty()) {
          emptyList()
        } else {
          listOf(
            EditorIssue(
              key,
              EditorIssueMessage.CASCADE_CHOICE_PARENT_VALUE_UNKNOWN.message(
                unknown.joinToString(", "),
                parent.name,
              ),
              isWarning = true,
            )
          )
        }
      }
    }
  }
}
