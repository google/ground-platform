import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

// The domain layer of shared/app (see docs/technical/client/modules.md): models, repository
// interfaces, use cases, and DomainError, in pure Kotlin. No Compose, no strings, and no data or
// presentation code: none of them is on this module's classpath.
plugins {
  id("collectone.kmp.android")
  id("collectone.detekt")
  id("collectone.kover")
}

abstract class GenerateAppBuildConfigTask : DefaultTask() {
  @get:Input abstract val appVersion: Property<String>

  @get:OutputDirectory abstract val outputDir: DirectoryProperty

  @TaskAction
  fun generate() {
    val root = outputDir.get().asFile
    root.deleteRecursively()
    val escaped = appVersion.get().replace("\\", "\\\\").replace("\"", "\\\"")
    val outFile = root.resolve("org/openforis/collectone/v2/app/domain/model/AppBuildConfig.kt")
    outFile.parentFile.mkdirs()
    outFile.writeText(
      "// Generated by build.gradle.kts; do not edit.\n" +
        "package org.openforis.collectone.v2.app.domain.model\n\n" +
        "/** Build-time client metadata sourced from Gradle `version` (or `APP_VERSION`). */\n" +
        "object AppBuildConfig {\n" +
        "  const val APP_VERSION: String = \"$escaped\"\n" +
        "}\n"
    )
  }
}

val iosEnabled = providers.gradleProperty("collectone.ios").orNull == "true"

val appVersionValue =
  (providers.gradleProperty("APP_VERSION").orNull
      ?: providers.environmentVariable("APP_VERSION").orNull
      ?: project.version.toString())
    .trim()

val generateAppBuildConfig by
  tasks.registering(GenerateAppBuildConfigTask::class) {
    appVersion.set(appVersionValue)
    outputDir.set(layout.buildDirectory.dir("generated/source/appBuildConfig"))
  }

kotlin {
  if (iosEnabled) {
    iosArm64()
    iosSimulatorArm64()
  }

  sourceSets {
    val commonMain by getting {
      kotlin.srcDir(generateAppBuildConfig.flatMap { it.outputDir })
      dependencies {
        api(projects.shared.core)
        // The map's geometry types (LatLng, LngLatBounds, Geometry), without Compose.
        api(projects.shared.map.geometry)
        // App-level dates and times (not the XForms engine, which keeps its own calendar code).
        api(libs.kotlinx.datetime)
      }
    }
    val commonTest by getting {
      dependencies {
        implementation(kotlin("test"))
        implementation(projects.shared.app.testing)
      }
    }
    val jvmTest by getting { dependencies { implementation(kotlin("test-junit5")) } }
  }
}

android { namespace = "org.openforis.collectone.v2.app.domain" }
